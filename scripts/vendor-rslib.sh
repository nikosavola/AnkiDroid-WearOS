#!/usr/bin/env bash
# Vendored Anki rslib scheduler sources under core/vendor/anki, kept byte-identical to upstream.
#
#   scripts/vendor-rslib.sh --check                 verify files against UPSTREAM.toml (offline)
#   scripts/vendor-rslib.sh --update <commit> [tag] fetch the file list at <commit>, rewrite hashes
#
# Bumping Anki: run --update with the new commit, review the diff, fix the shim/adapter.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/core/vendor/anki"
MANIFEST="$VENDOR/UPSTREAM.toml"
REPO="https://github.com/ankitects/anki"
RAW="https://raw.githubusercontent.com/ankitects/anki"

FILES=(
  LICENSE
  rslib/src/scheduler/states/filtered.rs
  rslib/src/scheduler/states/fuzz.rs
  rslib/src/scheduler/states/interval_kind.rs
  rslib/src/scheduler/states/learning.rs
  rslib/src/scheduler/states/load_balancer.rs
  rslib/src/scheduler/states/mod.rs
  rslib/src/scheduler/states/new.rs
  rslib/src/scheduler/states/normal.rs
  rslib/src/scheduler/states/preview_filter.rs
  rslib/src/scheduler/states/relearning.rs
  rslib/src/scheduler/states/rescheduling_filter.rs
  rslib/src/scheduler/states/review.rs
  rslib/src/scheduler/states/steps.rs
  rslib/src/scheduler/timespan.rs
)

sha256() {
  if command -v sha256sum >/dev/null; then
    sha256sum "$1" | cut -d' ' -f1
  else
    shasum -a 256 "$1" | cut -d' ' -f1
  fi
}

check() {
  [ -f "$MANIFEST" ] || { echo "error: $MANIFEST missing" >&2; exit 1; }
  local fail=0 path expected actual listed
  listed=$(grep -c '^"[^"]*" = "[0-9a-f]\{64\}"$' "$MANIFEST" || true)
  if [ "$listed" -ne "${#FILES[@]}" ]; then
    echo "error: manifest lists $listed files, script expects ${#FILES[@]}" >&2
    fail=1
  fi
  for path in "${FILES[@]}"; do
    expected=$(sed -n "s|^\"$path\" = \"\([0-9a-f]*\)\"$|\1|p" "$MANIFEST")
    if [ -z "$expected" ]; then
      echo "MISSING HASH $path" >&2
      fail=1
    elif [ ! -f "$VENDOR/$path" ]; then
      echo "MISSING FILE $path" >&2
      fail=1
    else
      actual=$(sha256 "$VENDOR/$path")
      if [ "$actual" != "$expected" ]; then
        echo "MODIFIED $path" >&2
        fail=1
      fi
    fi
  done
  if [ "$fail" -ne 0 ]; then
    echo "vendored rslib does not match UPSTREAM.toml; vendored files must stay verbatim" >&2
    exit 1
  fi
  echo "ok: ${#FILES[@]} vendored files match $(sed -n 's/^commit = "\(.*\)"$/\1/p' "$MANIFEST")"
}

update() {
  local commit="$1" tag="${2:-$1}" path
  TMP=$(mktemp -d)
  trap 'rm -rf "$TMP"' EXIT
  # Fetch everything first so a failed download leaves the vendored tree untouched.
  for path in "${FILES[@]}"; do
    mkdir -p "$TMP/$(dirname "$path")"
    curl -fsSL --retry 3 -o "$TMP/$path" "$RAW/$commit/$path"
  done
  {
    echo "# Generated by scripts/vendor-rslib.sh --update; do not edit by hand."
    echo "repo = \"$REPO\""
    echo "tag = \"$tag\""
    echo "commit = \"$commit\""
    echo
    echo "[files]"
    for path in "${FILES[@]}"; do
      echo "\"$path\" = \"$(sha256 "$TMP/$path")\""
    done
  } >"$TMP/UPSTREAM.toml"
  for path in "${FILES[@]}"; do
    mkdir -p "$VENDOR/$(dirname "$path")"
    cp "$TMP/$path" "$VENDOR/$path"
  done
  cp "$TMP/UPSTREAM.toml" "$MANIFEST"
  echo "updated ${#FILES[@]} files to $commit; review the diff"
}

case "${1:-}" in
  --check) check ;;
  --update)
    [ -n "${2:-}" ] || { echo "usage: $0 --update <commit> [tag]" >&2; exit 2; }
    update "$2" "${3:-}"
    ;;
  *)
    echo "usage: $0 --check | --update <commit> [tag]" >&2
    exit 2
    ;;
esac
